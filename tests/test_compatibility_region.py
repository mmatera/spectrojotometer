"""
Tests for the estimation of the compatibility region
{J : max_i |(A.J - E)_i| <= tol}: Monte Carlo box, exact box and
bound inequalities.
"""

import itertools

import numpy as np
import pytest

from spectrojotometer.magnetic_model import MagneticModel
from spectrojotometer.tools import box_ellipse, compatibility_box


def chain_model(n_sites=8, n_bonds=3):
    """Ring of n_sites with couplings up to the n_bonds-th neighbour."""
    pos = [np.array([float(i), 0.0, 0.0]) for i in range(n_sites)]
    lists = [
        [(i, (i + d) % n_sites, (0,)) for i in range(n_sites)]
        for d in range(1, n_bonds + 1)
    ]
    return MagneticModel(
        pos,
        [np.array([float(n_sites), 0.0, 0.0])],
        bond_lists=lists,
        bond_distances=list(range(1, n_bonds + 1)),
    )


def synthetic_problem(seed=0, n_sites=8, n_bonds=3, n_confs=12, tol=1.0e-3):
    """Energies generated by known couplings plus noise bounded by tol/2."""
    rng = np.random.default_rng(seed)
    model = chain_model(n_sites, n_bonds)
    confs = [[0] + list(rng.integers(0, 2, n_sites - 1)) for _ in range(n_confs)]
    coeffs = model.coefficient_matrix(confs, normalizar=True)
    while np.linalg.matrix_rank(coeffs) < n_bonds + 1:
        confs.append([0] + list(rng.integers(0, 2, n_sites - 1)))
        coeffs = model.coefficient_matrix(confs, normalizar=True)
    j_true = np.r_[rng.normal(0.0, 0.01, n_bonds), -100.0]
    energs = coeffs.dot(j_true) + rng.uniform(-tol / 2, tol / 2, len(confs))
    return model, confs, coeffs, energs, j_true, tol


@pytest.mark.parametrize("seed", range(5))
def test_montecarlo_box_is_unit_invariant(seed):
    """Rescaling energies and tolerance must rescale the result."""
    model, confs, _, energs, _, tol = synthetic_problem(seed)
    js1, dj1, chi1, rate1 = model.compute_couplings(
        confs, energs, tol, rng=seed, method="montecarlo"
    )
    scale = 1000.0  # eV -> meV
    js2, dj2, chi2, rate2 = model.compute_couplings(
        confs, scale * energs, scale * tol, rng=seed, method="montecarlo"
    )
    assert rate1 == rate2
    assert 0.0 < rate1 < 1.0
    np.testing.assert_allclose(scale * dj1, dj2, rtol=1e-6)
    np.testing.assert_allclose(scale * js1, js2, rtol=1e-9)
    np.testing.assert_allclose(chi1, chi2, rtol=1e-6, atol=1e-9)


@pytest.mark.parametrize("seed", range(5))
def test_montecarlo_box_inside_exact_box(seed):
    """Accepted points belong to the region, so the MC box is inside the
    exact one, and for low dimension it should be close to it."""
    model, confs, coeffs, energs, j_true, tol = synthetic_problem(
        seed, n_sites=6, n_bonds=2, n_confs=8
    )
    lower, upper = compatibility_box(coeffs, energs, tol)
    js, dj, _, rate = model.montecarlo_box(coeffs, energs, tol, 20000, rng=seed)
    assert rate > 0
    eps = 1e-9 * tol
    assert np.all(js - dj >= lower - eps)
    assert np.all(js + dj <= upper + eps)
    assert np.all((dj / (0.5 * (upper - lower)))[:-1] > 0.8)


@pytest.mark.parametrize("seed", range(5))
def test_exact_box_contains_truth_and_is_inside_ellipse_box(seed):
    _, _, coeffs, energs, j_true, tol = synthetic_problem(seed)
    lower, upper = compatibility_box(coeffs, energs, tol)
    assert np.all(lower <= j_true) and np.all(j_true <= upper)
    j_ls = np.linalg.lstsq(coeffs, energs, rcond=None)[0]
    radius = np.sqrt(
        len(energs) * tol**2 - np.sum((coeffs.dot(j_ls) - energs) ** 2)
    )
    half_ell = np.array(box_ellipse(coeffs, radius))
    assert np.all(0.5 * (upper - lower) <= half_ell * (1 + 1e-9))


def test_exact_box_detects_incompatibility_and_undetermined():
    coeffs = np.array([[1.0, 0.0], [1.0, 0.0]])
    # Contradictory equations for x0, nothing about x1.
    assert compatibility_box(coeffs, [0.0, 1.0], 0.1) is None
    lower, upper = compatibility_box(coeffs, [0.0, 0.05], 0.1)
    assert np.isclose(lower[0], -0.05) and np.isclose(upper[0], 0.1)
    assert lower[1] == -np.inf and upper[1] == np.inf


def test_montecarlo_box_undetermined_parameter():
    """A coupling that does not enter the equations is reported as nan."""
    coeffs = np.array([[1.0, 0.0, 1.0], [-1.0, 0.0, 1.0], [1.0, 0.0, 1.0]])
    energs = np.array([1.0, -1.0, 1.0])
    model = chain_model(4, 1)
    js, dj, _, rate = model.montecarlo_box(coeffs, energs, 0.1, 2000, rng=0)
    assert rate > 0
    assert np.isnan(dj[1]) and js[1] == 0.0
    assert np.all(np.isfinite(dj[[0, 2]]))


def test_montecarlo_box_incompatible_model():
    model, confs, coeffs, energs, _, tol = synthetic_problem(0)
    energs = energs + np.where(np.arange(len(energs)) % 2, 1.0, -1.0)
    js, dj, chi, rate = model.montecarlo_box(coeffs, energs, tol, rng=0)
    assert rate == 0.0
    assert np.all(dj == -1)


@pytest.mark.parametrize("seed", range(10))
def test_bound_inequalities_are_consistent(seed):
    """One finite constraint per determined direction, satisfied by the
    true couplings, and invariant under a change of energy units."""
    model, confs, _, energs, j_true, tol = synthetic_problem(seed)
    ineqs = model.bound_inequalities(confs, energs, err_energs=tol)
    assert len(ineqs) == len(model.bonds)
    for v, offset, delta in ineqs:
        assert np.isclose(np.max(np.abs(v)), 1.0)
        assert np.isfinite(offset) and np.isfinite(delta) and delta > 0
        assert abs(v.dot(j_true[:-1]) - offset) <= delta
    scaled = model.bound_inequalities(confs, 1000 * energs, err_energs=1000 * tol)
    for (v1, o1, d1), (v2, o2, d2) in zip(ineqs, scaled):
        np.testing.assert_allclose(v1, v2, atol=1e-9)
        np.testing.assert_allclose([1000 * o1, 1000 * d1], [o2, d2], rtol=1e-6)


def test_bound_inequalities_contain_exact_box():
    """Each constraint comes from an ellipsoid containing the region, so
    every vertex of the exact box projection must satisfy it."""
    model, confs, coeffs, energs, _, tol = synthetic_problem(3)
    lower, upper = compatibility_box(coeffs, energs, tol)
    # Points of the region: maximize/minimize each constraint direction.
    from scipy.optimize import linprog

    a_ub = np.vstack([coeffs, -coeffs])
    b_ub = np.r_[energs + tol, tol - energs]
    for v, offset, delta in model.bound_inequalities(confs, energs, tol):
        for sign in (1, -1):
            sol = linprog(
                sign * np.r_[v, 0.0], A_ub=a_ub, b_ub=b_ub, bounds=(None, None)
            )
            assert sol.status == 0
            assert abs(v.dot(sol.x[:-1]) - offset) <= delta * (1 + 1e-9)


def test_bound_inequalities_incompatible_returns_empty():
    model, confs, _, energs, _, tol = synthetic_problem(1)
    energs = energs + np.where(np.arange(len(energs)) % 2, 1.0, -1.0)
    assert model.bound_inequalities(confs, energs, tol) == []


@pytest.mark.parametrize("seed", range(5))
def test_compute_couplings_exact_is_default(seed):
    model, confs, coeffs, energs, j_true, tol = synthetic_problem(seed)
    js, dj, chi, rate = model.compute_couplings(confs, energs, tol)
    lower, upper = compatibility_box(coeffs, energs, tol)
    np.testing.assert_allclose(js, 0.5 * (upper + lower))
    np.testing.assert_allclose(dj, 0.5 * (upper - lower))
    assert rate == 1.0
    assert np.all(np.abs(js - j_true) <= dj * (1 + 1e-9))
    # unit invariance
    js2, dj2, _, _ = model.compute_couplings(confs, 1000 * energs, 1000 * tol)
    np.testing.assert_allclose(1000 * dj, dj2, rtol=1e-6)


def test_compute_couplings_method_ordering():
    """montecarlo box  <=  exact box  <=  ellipse box."""
    model, confs, _, energs, _, tol = synthetic_problem(2)
    _, d_mc, _, _ = model.compute_couplings(
        confs, energs, tol, method="montecarlo", mcsteps=5000, rng=0
    )
    _, d_ex, _, _ = model.compute_couplings(confs, energs, tol, method="exact")
    _, d_el, _, _ = model.compute_couplings(confs, energs, tol, method="ellipse")
    assert np.all(d_mc <= d_ex * (1 + 1e-9))
    assert np.all(d_ex <= np.asarray(d_el) * (1 + 1e-9))


def test_compute_couplings_legacy_montecarlo_flag():
    model, confs, _, energs, _, tol = synthetic_problem(0)
    _, _, _, rate = model.compute_couplings(confs, energs, tol, montecarlo=True, rng=0)
    assert 0 < rate < 1
    _, d_old, _, _ = model.compute_couplings(confs, energs, tol, montecarlo=False)
    _, d_el, _, _ = model.compute_couplings(confs, energs, tol, method="ellipse")
    np.testing.assert_allclose(d_old, d_el)
    with pytest.raises(ValueError):
        model.compute_couplings(confs, energs, tol, method="bogus")


def test_compute_couplings_exact_incompatible_and_undetermined():
    model, confs, _, energs, _, tol = synthetic_problem(1)
    bad = energs + np.where(np.arange(len(energs)) % 2, 1.0, -1.0)
    _, dj, _, rate = model.compute_couplings(confs, bad, tol)
    assert rate == 0.0 and np.all(dj == -1)
    # Only ferromagnetic-like configurations: J's are not determined.
    model = chain_model(8, 2)
    confs = [[0] * 8, [0] * 8]
    js, dj, _, _ = model.compute_couplings(confs, [1.0, 1.0], 0.01)
    assert np.all(np.isnan(dj[:-1])) and np.all(js[:-1] == 0)
    assert np.isfinite(dj[-1])
